const ignoredTags = [
    "SCRIPT",
    "STYLE",
    "NOSCRIPT"
];


// ======================================================
// 🧹 NORMALISER UN TEXTE
// ======================================================

function normalizeText(text) {

    return String(text || "")
        .replace(/\s+/g, " ")
        .trim();

}


// ======================================================
// 📖 TRADUIRE L'HISTOIRE DE GORÉE
// ======================================================

function translateHistory(text) {

    const normalized =
        normalizeText(text);

    if (!normalized) {
        return null;
    }

    for (
        const language of ["en", "wo"]
    ) {

        if (
            currentLanguage === language &&
            normalized.startsWith(
                HISTORY_TRANSLATIONS[language].marker
            )
        ) {

            return HISTORY_TRANSLATIONS[
                language
            ].text;

        }

    }

    return null;
}


// ======================================================
// 🔄 TRADUIRE UN TEXTE
// ======================================================

function translateText(text) {

    if (
        text === null ||
        text === undefined
    ) {
        return text;
    }

    const cleanText =
        normalizeText(text);

    if (!cleanText) {
        return text;
    }


    // ----------------------------------------------
    // 🇫🇷 FRANÇAIS
    // ----------------------------------------------

    if (
        currentLanguage === "fr"
    ) {

        return text;

    }


    // ----------------------------------------------
    // 📖 HISTOIRE
    // ----------------------------------------------

    const history =
        translateHistory(text);

    if (history) {

        return history;

    }


    // ----------------------------------------------
    // 📚 DICTIONNAIRE
    // ----------------------------------------------

    const dictionary =
        DICTIONARY[currentLanguage];

    if (!dictionary) {

        return text;

    }


    // ----------------------------------------------
    // CORRESPONDANCE EXACTE
    // ----------------------------------------------

    if (
        dictionary[cleanText]
    ) {

        return text.replace(
            cleanText,
            dictionary[cleanText]
        );

    }


    // ----------------------------------------------
    // TRADUIRE LES PHRASES CONNUES DANS LES TEXTES
    // PLUS LONGS (ex. une étiquette avec une valeur).
    // ----------------------------------------------

    const escapeRegExp = value =>
        value.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");

    const partialTranslation =
        Object.entries(dictionary)
            .filter(([source]) => source.trim().length > 1)
            .sort(([a], [b]) => b.length - a.length)
            .reduce((result, [source, translation]) => {
                const flexibleWhitespacePattern = source
                    .trim()
                    .split(/\s+/)
                    .map(escapeRegExp)
                    .join("\\s+");

                return result.replace(
                    new RegExp(flexibleWhitespacePattern, "gi"),
                    translation
                );
            }, text);

    if (partialTranslation !== text) {
        return partialTranslation;
    }


    // ----------------------------------------------
    // CORRESPONDANCE INSENSIBLE
    // À LA CASSE
    // ----------------------------------------------

    for (
        const [fr, translation]
        of Object.entries(dictionary)
    ) {

        if (
            cleanText.toLowerCase() ===
            fr.toLowerCase()
        ) {

            return text.replace(
                cleanText,
                translation
            );

        }

    }


    return text;

}


// ======================================================
// 🌍 TRADUCTION AUTOMATIQUE DU DOM
// ======================================================

function translateDOM() {

    if (
        !document.body
    ) {
        return;
    }


    const walker =
        document.createTreeWalker(
            document.body,
            NodeFilter.SHOW_TEXT
        );


    const nodes = [];

    let node;


    while (
        node = walker.nextNode()
    ) {

        const parent =
            node.parentElement;


        if (!parent) {
            continue;
        }


        if (
            ignoredTags.includes(
                parent.tagName
            )
        ) {

            continue;

        }


        nodes.push(node);

    }


    // ----------------------------------------------
    // TEXTES
    // ----------------------------------------------

    nodes.forEach(
        textNode => {

            const original =
                textNode.nodeValue;


            const translated =
                translateText(original);


            if (
                translated !== original
            ) {

                textNode.nodeValue =
                    translated;

            }

        }
    );


    // ----------------------------------------------
    // PLACEHOLDERS
    // ----------------------------------------------

    document
        .querySelectorAll(
            "input[placeholder], textarea[placeholder]"
        )
        .forEach(
            input => {

                const original =
                    input.getAttribute(
                        "placeholder"
                    );


                const translated =
                    translateText(original);


                if (
                    translated !== original
                ) {

                    input.setAttribute(
                        "placeholder",
                        translated
                    );

                }

            }
        );

}


// ======================================================
// 🌍 CHANGER DE LANGUE
// ======================================================

function setLanguage(language) {

    if (
        ![
            "fr",
            "en",
            "wo"
        ].includes(language)
    ) {

        console.error(
            "❌ Langue inconnue :",
            language
        );

        return;

    }


    currentLanguage =
        language;


    localStorage.setItem(
        "egoree-language",
        language
    );


    /*
     * On recharge la page afin de repartir
     * du texte français original.
     *
     * Cela évite les doubles traductions.
     */

    window.location.reload();

}


// ======================================================
// 🌍 LANGUE ACTUELLE
// ======================================================

function getCurrentLanguage() {

    return currentLanguage;

}


// ======================================================
// 🚀 INITIALISATION
// ======================================================

document.addEventListener(
    "DOMContentLoaded",
    () => {

        translateDOM();

        console.log(
            "🌍 E-Gorée langue :",
            currentLanguage
        );

    }
);


// ======================================================
// 🔄 ÉLÉMENTS AJOUTÉS DYNAMIQUEMENT
// ======================================================

const observer =
    new MutationObserver(
        mutations => {

            let shouldTranslate =
                false;


            mutations.forEach(
                mutation => {

                    if (
                        mutation.addedNodes &&
                        mutation.addedNodes.length
                    ) {

                        shouldTranslate =
                            true;

                    }

                }
            );


            if (
                shouldTranslate
            ) {

                translateDOM();

            }

        }
    );


document.addEventListener(
    "DOMContentLoaded",
    () => {

        observer.observe(
            document.body,
            {
                childList: true,
                subtree: true
            }
        );

    }
);


